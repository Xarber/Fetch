import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';

test('real media workflow, responsive layout, private API and offline shell',async({page,context})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Good media. Yours to keep.'})).toBeVisible();
 await page.getByRole('button',{name:'Connect server',exact:true}).click();
 await page.getByLabel('Password',{exact:true}).fill('browser-test-only-password-2026');
 await page.getByRole('button',{name:'Connect securely'}).click();
 await expect(page.getByRole('button',{name:'Sign out',exact:true})).toBeVisible();
 await page.locator('#source-url').fill(readFileSync('.qa/media-url.txt','utf8'));
 await page.getByRole('button',{name:'Inspect link'}).click();
 await expect(page.locator('#media-dialog')).toBeVisible();
 await page.locator('#preset').selectOption('audio');await page.locator('#audio-format').selectOption('mp3');
 await page.getByLabel('I’m authorized to save this media',{exact:true}).check();
 await page.getByRole('button',{name:'Fetch media'}).click();
 await expect(page.locator('#media-dialog')).not.toBeVisible();
 await expect(page.locator('#recent-jobs').getByRole('button',{name:'Save file'})).toBeVisible({timeout:30000});
 const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#recent-jobs').getByRole('button',{name:'Save file'}).click()]);
 expect(download.suggestedFilename()).toMatch(/\.mp3$/);
 await expect(page.locator('#toast')).toBeHidden({timeout:8000});
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:'docs/reports/dashboard-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Fetch 0.1.0 · development'}).click({clickCount:3,delay:100});
 await page.getByRole('button',{name:'Developer ideas'}).click();
 await page.getByRole('button',{name:'+ New idea'}).click();
 await page.getByLabel('Title',{exact:true}).fill('Browser test idea');
 await page.getByLabel('Description & reproduction steps').fill('Offline persistence check — synthetic QA entry');
 await page.getByRole('button',{name:'Save idea',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Browser test idea'})).toBeVisible();
 await page.locator('[data-view=overview]').click();
 await expect(page.getByRole('button',{name:'Developer ideas'})).not.toBeVisible();
 await page.setViewportSize({width:390,height:844});
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await expect(page.locator('#toast')).toBeHidden({timeout:8000});
 await page.screenshot({path:'docs/reports/dashboard-mobile.png',fullPage:true});
 await page.evaluate(async()=>{await navigator.serviceWorker.ready;});
 await page.reload();
 await context.setOffline(true);await page.reload();
 await expect(page.getByRole('heading',{name:'Good media. Yours to keep.'})).toBeVisible();
 expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('fetch.ideas.v1')??'{}').ideas.length)).toBe(1);
 const cachePaths=await page.evaluate(async()=>{const cache=await caches.open((await caches.keys())[0]!);return (await cache.keys()).map(r=>new URL(r.url).pathname);});
 expect(cachePaths.some(p=>p.startsWith('/api/'))).toBe(false);
 await context.setOffline(false);
 expect(errors).toEqual([]);
});
